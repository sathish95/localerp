-- ============================================================
-- STEP182: Industry-Adaptive Platform — Phase 4 Universal Task Engine.
--
-- Fully additive except for ONE constraint relaxation on an existing
-- column, done unconditionally because it is provably safe regardless
-- of that column's current state (see note above the ALTER below).
-- No existing row, RLS policy, or column type changes. See
-- docs/industry-adaptive/EXISTING_SYSTEM_ANALYSIS.md §13 for why the
-- base `project_tasks` schema has no tracked CREATE TABLE to diff
-- against, and why that fact does not block this migration.
--
-- What this adds:
--   work_type_configs — org-scoped lookup of work-item types (Work
--                       Order, Service Request, Production Order, ...).
--                       Seeded with the master prompt's §12 list for
--                       every existing org, same "additive default data"
--                       posture as STEP180's industry_profiles seed.
--   work_items         — the generic non-Project parent a Task may
--                       optionally belong to instead of (or in addition
--                       to) a Project.
--   project_tasks.work_item_id  — new nullable soft-ref column.
--   project_tasks.checklist     — new JSONB column, default '[]', for
--                       the master prompt §19 checklist-item shape.
--                       Array column chosen over a relational table for
--                       this first pass — see MIGRATION_PLAN.md-style
--                       reasoning: a task's checklist is always read/
--                       written as one whole unit with its task, never
--                       queried independently, so JSONB avoids a join
--                       for zero practical loss. Revisit only if a
--                       future phase needs to query across checklists.
--   project_tasks.recurrence_rule — new nullable JSONB column, CONFIG
--                       STORAGE ONLY. No scheduler/cron exists in this
--                       repo (grepped for pg_cron/cron.schedule/a
--                       supabase/functions dir — none found) and this
--                       migration does not add one. A recurring task's
--                       *next occurrence* is not generated by anything
--                       yet; this column exists so the UI can save the
--                       intended rule without the data being thrown away,
--                       ahead of a future phase actually acting on it.
--   task_templates      — org-scoped, admin/manager-writable (tighter
--                       than work_items: this is configuration, not
--                       day-to-day operational data, mirroring how
--                       workspace_profiles itself is admin/ceo-gated).
--   task_contributors   — NEW, separate, optional join table for
--                       multiple people on one task. Does NOT touch or
--                       repurpose project_tasks.assigned_to in any way —
--                       that remains the single primary owner exactly as
--                       every existing code path already assumes.
--   work_logs           — Phase 5 prep (execution/WorkLog engine is next
--                       phase's job, not this one's) — table exists now
--                       so Phase 5 has zero migration lead time, but
--                       nothing in this phase writes to it.
--
-- The ONE relaxed constraint:
--   ALTER TABLE project_tasks ALTER COLUMN project_id DROP NOT NULL;
--   This statement is idempotent and safe regardless of the column's
--   current state — Postgres does not error if no NOT NULL constraint
--   exists; it simply ensures the column ends up nullable either way.
--   This is how "Task becomes Project-optional" is achieved without
--   needing a live information_schema query first (STEP180's own
--   diagnostic-dump recommendation is still worth running separately,
--   but this migration does not depend on its result).
--   project_tasks already has organization_id (added+backfilled+NOT
--   NULL'd by STEP96_rls_batch_uniform_open.sql, independent of
--   project_id) — so a project-less task is still fully org-scoped by
--   RLS with zero change needed there.
-- ============================================================

-- ── work_type_configs ────────────────────────────────────────
CREATE TABLE IF NOT EXISTS work_type_configs (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id UUID NOT NULL DEFAULT current_org_id() REFERENCES organizations(id),
  key             TEXT NOT NULL,
  name            TEXT NOT NULL,
  icon            TEXT,
  active          BOOLEAN NOT NULL DEFAULT true,
  created_at      TIMESTAMPTZ DEFAULT now(),
  UNIQUE (organization_id, key)
);

INSERT INTO work_type_configs (organization_id, key, name, icon)
SELECT o.id, wt.key, wt.name, wt.icon
FROM organizations o
CROSS JOIN (VALUES
  ('work_order',        'Work Order',        'ClipboardList'),
  ('service_request',   'Service Request',   'LifeBuoy'),
  ('production_order',  'Production Order',  'Factory'),
  ('maintenance_order', 'Maintenance Order', 'Wrench'),
  ('inspection',        'Inspection',        'ClipboardCheck'),
  ('visit',             'Visit',             'MapPin'),
  ('delivery',          'Delivery',          'Truck'),
  ('patrol',            'Patrol',            'ShieldCheck'),
  ('shift_duty',        'Shift Duty',        'Clock'),
  ('direct_work',       'Direct Work',       'ListChecks')
) AS wt(key, name, icon)
ON CONFLICT (organization_id, key) DO NOTHING;

-- ── work_items ───────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS work_items (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id UUID NOT NULL DEFAULT current_org_id() REFERENCES organizations(id),
  work_type_key   TEXT NOT NULL, -- soft ref -> work_type_configs.key (not a hard FK: key is the stable
                                  -- identity, not the row id, so a reseed of work_type_configs never
                                  -- orphans a work_item)
  title           TEXT NOT NULL,
  client_id       UUID, -- soft ref, nullable (no clients/CRM-contacts table confirmed generic enough yet)
  location_id     UUID, -- soft ref, nullable — no `locations` table exists yet (Phase 6); forward-looking only
  department_id   UUID, -- soft ref -> departments(id), nullable
  status          TEXT NOT NULL DEFAULT 'open',
  custom_fields   JSONB DEFAULT '{}',
  created_by      UUID REFERENCES profiles(id),
  created_at      TIMESTAMPTZ DEFAULT now(),
  updated_at      TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS work_items_org_idx ON work_items(organization_id, status);

DROP TRIGGER IF EXISTS work_items_updated_at ON work_items;
CREATE TRIGGER work_items_updated_at BEFORE UPDATE ON work_items
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ── project_tasks: additive columns + the one constraint relaxation ──
ALTER TABLE project_tasks ADD COLUMN IF NOT EXISTS work_item_id UUID; -- soft ref -> work_items(id)
ALTER TABLE project_tasks ADD COLUMN IF NOT EXISTS checklist JSONB NOT NULL DEFAULT '[]'::jsonb;
ALTER TABLE project_tasks ADD COLUMN IF NOT EXISTS recurrence_rule JSONB; -- config storage only, see header
ALTER TABLE project_tasks ALTER COLUMN project_id DROP NOT NULL;

-- ── task_templates ───────────────────────────────────────────
CREATE TABLE IF NOT EXISTS task_templates (
  id                UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id   UUID NOT NULL DEFAULT current_org_id() REFERENCES organizations(id),
  name              TEXT NOT NULL,
  task_type         TEXT,
  default_checklist JSONB NOT NULL DEFAULT '[]'::jsonb,
  estimated_hours   NUMERIC,
  requires_approval BOOLEAN NOT NULL DEFAULT false,
  created_by        UUID REFERENCES profiles(id),
  created_at        TIMESTAMPTZ DEFAULT now()
);

-- ── task_contributors (separate from assigned_to — never repurposes it) ──
CREATE TABLE IF NOT EXISTS task_contributors (
  id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  task_id    UUID NOT NULL, -- soft ref -> project_tasks(id)
  person_id  UUID NOT NULL REFERENCES profiles(id),
  added_by   UUID REFERENCES profiles(id),
  created_at TIMESTAMPTZ DEFAULT now(),
  UNIQUE (task_id, person_id)
);
CREATE INDEX IF NOT EXISTS task_contributors_task_idx ON task_contributors(task_id);

-- ── work_logs (Phase 5 prep — created now, unused until Phase 5) ─────
CREATE TABLE IF NOT EXISTS work_logs (
  id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id  UUID NOT NULL DEFAULT current_org_id() REFERENCES organizations(id),
  employee_id      UUID NOT NULL REFERENCES profiles(id),
  task_id          UUID, -- soft ref -> project_tasks(id)
  checkin_log_id   UUID, -- soft ref -> time_logs(id), nullable (task work outside any check-in is allowed)
  work_item_id     UUID, -- soft ref -> work_items(id), nullable
  project_id       UUID, -- soft ref -> projects(id), nullable
  started_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  ended_at         TIMESTAMPTZ,
  duration_minutes INT,
  description      TEXT,
  evidence_urls    TEXT[],
  created_at       TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS work_logs_task_idx ON work_logs(task_id);
CREATE INDEX IF NOT EXISTS work_logs_employee_idx ON work_logs(employee_id);

-- ── RLS ──────────────────────────────────────────────────────
ALTER TABLE work_type_configs ENABLE ROW LEVEL SECURITY;
ALTER TABLE work_items        ENABLE ROW LEVEL SECURITY;
ALTER TABLE task_templates    ENABLE ROW LEVEL SECURITY;
ALTER TABLE task_contributors ENABLE ROW LEVEL SECURITY;
ALTER TABLE work_logs         ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS work_type_configs_select ON work_type_configs;
DROP POLICY IF EXISTS work_type_configs_write  ON work_type_configs;
CREATE POLICY work_type_configs_select ON work_type_configs FOR SELECT USING (
  organization_id = current_org_id() OR is_platform_super_admin()
);
CREATE POLICY work_type_configs_write ON work_type_configs FOR ALL USING (
  is_platform_super_admin() OR (
    organization_id = current_org_id() AND
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role IN ('admin','ceo'))
  )
) WITH CHECK (
  is_platform_super_admin() OR (
    organization_id = current_org_id() AND
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role IN ('admin','ceo'))
  )
);

-- work_items: day-to-day operational data — any org member can read/write
-- within their own org, mirroring project_tasks' own STEP96 "open" policy
-- shape (organization_id = current_org_id(), no extra role gate).
DROP POLICY IF EXISTS work_items_select ON work_items;
DROP POLICY IF EXISTS work_items_write  ON work_items;
CREATE POLICY work_items_select ON work_items FOR SELECT USING (organization_id = current_org_id());
CREATE POLICY work_items_write  ON work_items FOR ALL
  USING (organization_id = current_org_id()) WITH CHECK (organization_id = current_org_id());

-- task_templates: configuration, not operational data — admin/ceo/manager
-- write, same posture as workspace_profiles.
DROP POLICY IF EXISTS task_templates_select ON task_templates;
DROP POLICY IF EXISTS task_templates_write  ON task_templates;
CREATE POLICY task_templates_select ON task_templates FOR SELECT USING (organization_id = current_org_id());
CREATE POLICY task_templates_write ON task_templates FOR ALL USING (
  organization_id = current_org_id() AND
  EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role IN ('admin','ceo','manager','department_head'))
) WITH CHECK (
  organization_id = current_org_id() AND
  EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role IN ('admin','ceo','manager','department_head'))
);

-- task_contributors: scoped via its parent task's organization_id (the
-- table itself carries no organization_id column, matching how
-- workspace_operating_models is scoped via its parent's org, not its own).
-- ::text casts: this org's live project_tasks.id/organization_id type
-- couldn't be confirmed from tracked migrations (untracked base schema,
-- see this file's header) and turned out to throw "operator does not
-- exist: uuid = text" on a plain comparison — comparing as text works
-- regardless of which side is the actual UUID and which is TEXT.
DROP POLICY IF EXISTS task_contributors_select ON task_contributors;
DROP POLICY IF EXISTS task_contributors_write  ON task_contributors;
CREATE POLICY task_contributors_select ON task_contributors FOR SELECT USING (
  EXISTS (SELECT 1 FROM project_tasks pt WHERE pt.id::text = task_id::text AND pt.organization_id::text = current_org_id()::text)
);
CREATE POLICY task_contributors_write ON task_contributors FOR ALL USING (
  EXISTS (SELECT 1 FROM project_tasks pt WHERE pt.id::text = task_id::text AND pt.organization_id::text = current_org_id()::text)
) WITH CHECK (
  EXISTS (SELECT 1 FROM project_tasks pt WHERE pt.id::text = task_id::text AND pt.organization_id::text = current_org_id()::text)
);

DROP POLICY IF EXISTS work_logs_select ON work_logs;
DROP POLICY IF EXISTS work_logs_write  ON work_logs;
CREATE POLICY work_logs_select ON work_logs FOR SELECT USING (organization_id = current_org_id());
CREATE POLICY work_logs_write  ON work_logs FOR ALL
  USING (organization_id = current_org_id()) WITH CHECK (organization_id = current_org_id());

