-- ============================================================
-- STEP122: Seeds 10 ready-to-use, already-PUBLISHED certificate
-- templates — one per the spec's 9 example award categories (creating
-- those categories too, if they don't already exist) plus a 10th
-- generic fallback template (award_category_id NULL) used whenever an
-- award's category has no dedicated template. HR can still edit,
-- duplicate, re-color or replace any of these from Certificate
-- Templates — this is starting content, not a hardcoded set (categories
-- and templates both remain fully HR-editable after this runs).
--
-- All 10 share one layout (border, title, recipient name, award name/
-- category line, manager+HR signature blocks, QR code, certificate
-- number) generated by a helper function, differentiated by accent
-- color per category. The helper is dropped at the end of this
-- migration — it only exists to avoid repeating an 18-element JSONB
-- literal ten times, not as a permanent schema object.
--
-- Idempotent: re-running this migration skips any org/category that
-- already has a certificate template (checked before each insert), so
-- it won't duplicate templates or clobber ones HR has since edited.
-- ============================================================

CREATE OR REPLACE FUNCTION _seed_certificate_elements(accent TEXT)
RETURNS JSONB AS $$
  SELECT jsonb_build_array(
    jsonb_build_object('id','border_outer','type','shape','x',20,'y',20,'width',1160,'height',809,'zIndex',0,'shapeType','rect','borderColor',accent,'borderWidth',6,'filled',false,'fillColor','#ffffff'),
    jsonb_build_object('id','border_inner','type','shape','x',40,'y',40,'width',1120,'height',769,'zIndex',1,'shapeType','rect','borderColor',accent,'borderWidth',1.5,'filled',false,'fillColor','#ffffff'),
    jsonb_build_object('id','logo','type','image','x',60,'y',60,'width',120,'height',60,'zIndex',2,'variableKey','company_logo','imageSrc',null),
    jsonb_build_object('id','title','type','text','x',100,'y',80,'width',1000,'height',60,'zIndex',3,'content','CERTIFICATE OF ACHIEVEMENT','fontSize',34,'fontFamily','times','color',accent,'align','center','bold',true,'italic',false,'underline',false),
    jsonb_build_object('id','company','type','text','x',100,'y',148,'width',1000,'height',30,'zIndex',4,'content','{{company_name}}','fontSize',14,'fontFamily','helvetica','color','#64748b','align','center','bold',false,'italic',false,'underline',false),
    jsonb_build_object('id','presented','type','text','x',100,'y',248,'width',1000,'height',30,'zIndex',5,'content','This certificate is proudly presented to','fontSize',15,'fontFamily','times','color','#334155','align','center','bold',false,'italic',true,'underline',false),
    jsonb_build_object('id','employee_name','type','text','x',100,'y',292,'width',1000,'height',70,'zIndex',6,'content','{{employee_name}}','fontSize',42,'fontFamily','times','color','#111111','align','center','bold',true,'italic',false,'underline',false),
    jsonb_build_object('id','name_line','type','shape','x',400,'y',380,'width',400,'height',0,'zIndex',7,'shapeType','line','borderColor',accent,'borderWidth',2),
    jsonb_build_object('id','for_text','type','text','x',100,'y',396,'width',1000,'height',26,'zIndex',8,'content','for outstanding recognition as','fontSize',14,'fontFamily','helvetica','color','#334155','align','center','bold',false,'italic',false,'underline',false),
    jsonb_build_object('id','award_name','type','text','x',100,'y',426,'width',1000,'height',44,'zIndex',9,'content','{{award_name}}','fontSize',26,'fontFamily','times','color',accent,'align','center','bold',true,'italic',false,'underline',false),
    jsonb_build_object('id','award_meta','type','text','x',100,'y',476,'width',1000,'height',26,'zIndex',10,'content','under the {{award_category}} category - awarded {{award_date}}','fontSize',13,'fontFamily','helvetica','color','#64748b','align','center','bold',false,'italic',false,'underline',false),
    jsonb_build_object('id','mgr_line','type','shape','x',180,'y',668,'width',260,'height',0,'zIndex',11,'shapeType','line','borderColor','#94a3b8','borderWidth',1),
    jsonb_build_object('id','mgr_name','type','text','x',180,'y',676,'width',260,'height',24,'zIndex',12,'content','{{manager_name}}','fontSize',13,'fontFamily','helvetica','color','#111111','align','center','bold',true,'italic',false,'underline',false),
    jsonb_build_object('id','mgr_label','type','text','x',180,'y',702,'width',260,'height',20,'zIndex',13,'content','Manager','fontSize',10,'fontFamily','helvetica','color','#64748b','align','center','bold',false,'italic',false,'underline',false),
    jsonb_build_object('id','hr_line','type','shape','x',760,'y',668,'width',260,'height',0,'zIndex',14,'shapeType','line','borderColor','#94a3b8','borderWidth',1),
    jsonb_build_object('id','hr_name','type','text','x',760,'y',676,'width',260,'height',24,'zIndex',15,'content','{{hr_name}}','fontSize',13,'fontFamily','helvetica','color','#111111','align','center','bold',true,'italic',false,'underline',false),
    jsonb_build_object('id','hr_label','type','text','x',760,'y',702,'width',260,'height',20,'zIndex',16,'content','Human Resources','fontSize',10,'fontFamily','helvetica','color','#64748b','align','center','bold',false,'italic',false,'underline',false),
    jsonb_build_object('id','qr','type','qrcode','x',1040,'y',730,'width',70,'height',70,'zIndex',17),
    jsonb_build_object('id','cert_no','type','text','x',60,'y',760,'width',400,'height',20,'zIndex',18,'content','{{certificate_number}}','fontSize',9,'fontFamily','helvetica','color','#94a3b8','align','left','bold',false,'italic',false,'underline',false)
  );
$$ LANGUAGE sql IMMUTABLE;

DO $$
DECLARE
  org RECORD;
  cats TEXT[][] := ARRAY[
    ARRAY['Best Performer','Recognizing consistently excellent performance','#6366f1'],
    ARRAY['Employee of the Month','Awarded monthly for standout contribution','#0ea5e9'],
    ARRAY['Employee of the Year','Top annual recognition across the company','#f59e0b'],
    ARRAY['Innovation Award','Recognizing creative problem-solving and new ideas','#8b5cf6'],
    ARRAY['Leadership Excellence','Recognizing exceptional leadership qualities','#1d4ed8'],
    ARRAY['Team Player','Recognizing outstanding collaboration and teamwork','#10b981'],
    ARRAY['Customer Excellence','Recognizing exceptional customer service','#ec4899'],
    ARRAY['Outstanding Contribution','Recognizing significant impact and contribution','#f97316'],
    ARRAY['Rising Star','Recognizing high-potential emerging talent','#eab308']
  ];
  category_id UUID;
  template_id UUID;
BEGIN
  FOR org IN SELECT id FROM organizations LOOP
    FOR i IN 1..array_length(cats, 1) LOOP
      INSERT INTO award_categories (organization_id, name, description)
      VALUES (org.id, cats[i][1], cats[i][2])
      ON CONFLICT (organization_id, name) DO NOTHING;

      SELECT id INTO category_id FROM award_categories WHERE organization_id = org.id AND name = cats[i][1];

      IF NOT EXISTS (
        SELECT 1 FROM award_certificate_templates WHERE organization_id = org.id AND award_category_id = category_id
      ) THEN
        INSERT INTO award_certificate_templates (
          organization_id, name, award_category_id, status, page_size, orientation,
          canvas_width, canvas_height, background_color, elements, version
        ) VALUES (
          org.id, cats[i][1] || ' Certificate', category_id, 'active', 'A4', 'landscape',
          1200, 849, '#ffffff', _seed_certificate_elements(cats[i][3]), 1
        ) RETURNING id INTO template_id;

        INSERT INTO award_certificate_template_versions (
          organization_id, template_id, version, name, page_size, orientation,
          canvas_width, canvas_height, background_color, elements
        ) VALUES (
          org.id, template_id, 1, cats[i][1] || ' Certificate', 'A4', 'landscape',
          1200, 849, '#ffffff', _seed_certificate_elements(cats[i][3])
        );
      END IF;
    END LOOP;

    IF NOT EXISTS (
      SELECT 1 FROM award_certificate_templates WHERE organization_id = org.id AND award_category_id IS NULL
    ) THEN
      INSERT INTO award_certificate_templates (
        organization_id, name, award_category_id, status, page_size, orientation,
        canvas_width, canvas_height, background_color, elements, version
      ) VALUES (
        org.id, 'General Achievement Certificate', NULL, 'active', 'A4', 'landscape',
        1200, 849, '#ffffff', _seed_certificate_elements('#6366f1'), 1
      ) RETURNING id INTO template_id;

      INSERT INTO award_certificate_template_versions (
        organization_id, template_id, version, name, page_size, orientation,
        canvas_width, canvas_height, background_color, elements
      ) VALUES (
        org.id, template_id, 1, 'General Achievement Certificate', 'A4', 'landscape',
        1200, 849, '#ffffff', _seed_certificate_elements('#6366f1')
      );
    END IF;
  END LOOP;
END $$;

DROP FUNCTION IF EXISTS _seed_certificate_elements(TEXT);

NOTIFY pgrst, 'reload schema';
